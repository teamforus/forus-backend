$gelrepasAgeFormula = static function (int $amount, int $minAge, ?int $maxAge = null): array {
    $conditions = [[
        'record_type_key' => 'birth_date',
        'operator' => '<=',
        'value' => now()->subYears($minAge)->format('Y-m-d'),
    ]];

    if ($maxAge !== null) {
        $conditions[] = [
            'record_type_key' => 'birth_date',
            'operator' => '>',
            'value' => now()->subYears($maxAge + 1)->format('Y-m-d'),
        ];
    }

    return ['type' => 'fixed', 'amount' => $amount, 'conditions' => $conditions];
};

